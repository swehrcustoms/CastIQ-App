async function seedLakes(): Promise<void> {
  console.log(`Seeding ${TIER_1_LAKES.length} Tier 1 lakes...`);
  const batch = db.batch();
  const now = Timestamp.now();

  for (const lake of TIER_1_LAKES) {
    const ref = db.collection('lakes').doc(lake.lakeId);
    batch.set(
      ref,
      {
        ...lake,
        center: new GeoPoint(lake.lat, lake.lng),
        coordinates: { lat: lake.lat, lng: lake.lng, geohash: '' },
        lastSurveyDate: null,
        lastStockDate: null,
        lastReportDate: null,
        createdAt: now,
        updatedAt: now,
      },
      { merge: true }
    );
  }

  await batch.commit();
  console.log(`✓ ${TIER_1_LAKES.length} lakes seeded`);
}

seedLakes().catch((err) => {
  console.error('Seed failed:', err);
  process.exit(1);
});
